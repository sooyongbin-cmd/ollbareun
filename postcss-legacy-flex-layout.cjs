/* eslint-disable @typescript-eslint/no-require-imports -- Next loads PostCSS plugin factories with require(). */
const fs = require("node:fs");
const path = require("node:path");
const { Features, transform } = require(require.resolve("lightningcss", {
  paths: [path.dirname(require.resolve("@tailwindcss/node"))],
}));

const globalStyles = path.join(__dirname, "src", "app", "globals.css");
const output = path.join(__dirname, "public", "legacy-flex-layout.css");
const safari13 = { safari: (13 << 16) | (1 << 8) | 3 };
const layoutProperty = /^(?:display|position|box-sizing|order|gap|row-gap|column-gap|(?:align|justify|place)-[a-z-]+|(?:flex|grid|inset|overflow|margin|padding)(?:-[a-z-]+)?|(?:min-|max-)?(?:width|height|inline-size|block-size)|top|right|bottom|left|aspect-ratio|visibility|--tw-space-[xy]-reverse|font|font-(?:size|family|weight|style)|line-height|letter-spacing|white-space|word-break|content|clip|clip-path|vertical-align|border(?:-(?:top|right|bottom|left))?(?:-(?:width|style))?|border-collapse)$/;

// Tailwind emits :is(.utility > *) for child variants and
// .utility:is(:where(.group)[data-state] *) for group and peer variants.
function lowerUtilitySelector(selector) {
  const output = [];
  for (const part of selector) {
    if ((part.kind !== "is" && part.kind !== "where") || part.selectors.length !== 1) {
      output.push(part);
      continue;
    }
    const nested = lowerUtilitySelector(part.selectors[0]);
    if (!output.length) {
      output.push(...nested);
    } else if (nested.length > 1 && nested.at(-1).type === "universal") {
      output.unshift(...nested.slice(0, -1));
    } else if (nested.every(item => item.type !== "combinator")) {
      if (nested[0].type === "type" && output.at(-1).type === "universal") output.pop();
      output.push(...nested);
    } else {
      output.push(part);
    }
  }
  return output;
}

function buildLayoutStyles(root, postcss) {
  const layers = root.nodes.filter(node => node.type === "atrule" && node.name === "layer" && node.nodes);
  if (!layers.some(layer => layer.params === "utilities")) return null;

  // Tailwind's development output has nested variants; production can already be flat.
  const source = ["base", "components", "utilities"]
    .flatMap(name => layers.filter(layer => layer.params === name).flatMap(layer => layer.nodes))
    .map(node => node.toString()).join("\n");
  const flattened = transform({
    filename: "utilities.css",
    code: Buffer.from(source),
    targets: safari13,
    minify: false,
  });
  const legacy = postcss.parse(flattened.code.toString());
  // Safari 13 drops an entire selector list when one pseudo-element is unknown.
  legacy.walkRules(rule => {
    const list = /^:where\(([^()]*)\)$/.exec(rule.selector);
    if (list) rule.selector = list[1];
    if (!rule.selector.includes("::backdrop")) return;
    const supported = rule.selectors.filter(selector => !selector.includes("::backdrop"));
    if (supported.length) rule.selectors = supported;
    else rule.remove();
  });
  legacy.walkDecls(decl => {
    if (!layoutProperty.test(decl.prop)) decl.remove();
  });
  function removeEmpty(node) {
    if (node.type === "decl") return;
    if (node.nodes) node.each(removeEmpty);
    if (!node.nodes?.length) node.remove();
  }
  legacy.each(removeEmpty);

  // The normal theme is in a cascade layer, which Safari 13 discards.
  const theme = new Map();
  root.walkAtRules("layer", layer => {
    if (layer.params === "theme") layer.walkDecls(/^--/, decl => theme.set(decl.prop, decl));
  });
  // The project uses Tailwind's root spacing scale. Resolving it here also
  // lets Lightning CSS lower logical/inset shorthands containing calc().
  const spacing = theme.get("--spacing")?.value;
  if (spacing) legacy.walkDecls(decl => {
    decl.value = decl.value.replaceAll("var(--spacing)", spacing);
  });
  const needed = new Set();
  const collectVariables = value => {
    for (const match of value.matchAll(/var\(\s*(--[\w-]+)/g)) needed.add(match[1]);
  };
  legacy.walkDecls(decl => collectVariables(decl.value));
  const defaults = postcss.rule({ selector: ":root" });
  for (const name of needed) {
    const definition = theme.get(name);
    if (!definition) continue;
    defaults.append(definition.clone());
    collectVariables(definition.value);
  }
  if (defaults.nodes.length) legacy.prepend(defaults);
  const compatible = transform({
    filename: "legacy-flex-layout.css",
    code: Buffer.from(legacy.toString()),
    targets: safari13,
    include: Features.LogicalProperties,
    visitor: { Selector: lowerUtilitySelector },
    minify: false,
  });
  return "/* Generated by postcss-legacy-flex-layout.cjs. Loaded only for browsers without Flexbox gap. */\n" + compatible.code.toString();
}

module.exports = () => ({
  postcssPlugin: "legacy-flex-layout",
  OnceExit(root, { result, postcss }) {
    if (!result.opts.from || path.resolve(result.opts.from) !== globalStyles) return;
    const css = buildLayoutStyles(root, postcss);
    if (css === null || (fs.existsSync(output) && fs.readFileSync(output, "utf8") === css)) return;
    const temp = output + "." + process.pid + ".tmp";
    fs.writeFileSync(temp, css);
    fs.renameSync(temp, output);
  },
});
module.exports.postcss = true;
